# 任务三：全班成绩单（综合）
# 写函数 report(students)，students 是一个字典：键是名字、值是分数，例如
#   {'小明': 88, '小红': 95, '小刚': 74, '小美': 90}
# 函数要完成三件事：
#   1. 遍历字典，打印每个人的「名字 + 分数 + 等级」（等级调用任务一的 grade()）
#   2. 打印全班平均分（调用任务二 average()，先把字典里的分数转成列表）
#   3. 找出并打印最高分、最低分的人（提示：max / min，或自己写循环）
# 提示：students.values() 拿到所有分数，外面套一层 list() 就变列表
# ------------------------------------------------------------
def report(students):
    # TODO: 在这里写你的代码
    for i in students:
        print(f'\t名字:{i} 分数:{students[i]} 等级:{grade(students[i])}')

    print(average(list(students.values())))

    for _ in students:
        if students[_] == max(students.values()):
            print(_)
        elif students[_] == min(students.values()):
            print(_)


