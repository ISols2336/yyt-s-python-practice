# 任务一：分数转等级（热身）
# 写函数 grade(score)，传入一个 0~100 的分数，返回对应等级：
#   90 及以上 → 'A'
#   80~89     → 'B'
#   70~79     → 'C'
#   60~69     → 'D'
#   60 以下   → 'E'
# 提示：用 if / elif / else（你 practice07 里写过一模一样的逻辑）
# ------------------------------------------------------------
def grade(score):
    # TODO: 在这里写你的代码
    if score >= 90:
        return 'A'

    elif score >= 80:
        return 'B'

    elif score >= 70:
        return 'C'

    elif score >= 60:
        return 'D'

    else :
        return 'E'


# ------------------------------------------------------------
# 任务二：算平均分
# 写函数 average(scores)，scores 是一个装着分数的列表，比如 [85, 92, 78]，
# 返回它们的平均分，保留 1 位小数。
# 提示：sum() 求和、len() 求个数、round(x, 1) 保留一位小数
# ------------------------------------------------------------
def average(scores):
    # TODO: 在这里写你的代码
    res = sum(scores)/len(scores)
    res = round(res,1)
    return res


